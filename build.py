#!/usr/bin/env python3
"""Indexer: scans notes/**/*.md and writes viewer/graph-data.js.

Standard library only. Node ids equal their index in GRAPH.nodes.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.abspath(__file__))
NOTES_DIR = os.path.join(ROOT, "notes")
OUT_FILE = os.path.join(ROOT, "viewer", "graph-data.js")
EXCERPT_LEN = 700

WIKILINK_RE = re.compile(r"\[\[([^\]|#]+)(?:[#|][^\]]*)?\]\]")


def load_notes(notes_dir=NOTES_DIR):
    """Return notes sorted by path, each a dict with label, group, path, text."""
    notes = []
    for dirpath, _, filenames in os.walk(notes_dir):
        for name in filenames:
            if not name.lower().endswith(".md"):
                continue
            path = os.path.join(dirpath, name)
            with open(path, encoding="utf-8") as f:
                text = f.read()
            rel_dir = os.path.relpath(dirpath, notes_dir)
            group = "root" if rel_dir == "." else os.path.basename(dirpath)
            notes.append({
                "label": os.path.splitext(name)[0],
                "group": group,
                "path": os.path.relpath(path, ROOT).replace(os.sep, "/"),
                "text": text,
            })
    notes.sort(key=lambda n: n["path"].lower())
    return notes


def make_excerpt(text, limit=EXCERPT_LEN):
    # Drop a leading H1 (it duplicates the label) and unwrap wikilinks.
    body = re.sub(r"^\s*#\s+[^\n]*\n", "", text, count=1)
    body = WIKILINK_RE.sub(lambda m: m.group(1), body)
    body = re.sub(r"\*\*|__|`", "", body)                      # bold / code markers
    body = re.sub(r"^#{1,6}\s*", "", body, flags=re.M).strip()  # sub-headings
    if len(body) <= limit:
        return body
    cut = body[:limit]
    space = cut.rfind(" ")
    return (cut[:space] if space > limit * 0.8 else cut).rstrip() + "…"


def build_links(notes):
    """Link notes when one mentions another's title, or both share a wikilink target."""
    lowered = [n["text"].lower() for n in notes]
    wikis = [{w.strip().lower() for w in WIKILINK_RE.findall(n["text"])} for n in notes]
    pairs = {}

    def add(a, b, kind):
        if a == b:
            return
        key = (min(a, b), max(a, b))
        pairs.setdefault(key, set()).add(kind)

    for i, note in enumerate(notes):
        title = note["label"].lower()
        pattern = re.compile(r"(?<![\w])" + re.escape(title) + r"(?![\w])")
        for j in range(len(notes)):
            if j != i and pattern.search(lowered[j]):
                add(i, j, "mention")

    for i in range(len(notes)):
        for j in range(i + 1, len(notes)):
            if wikis[i] & wikis[j]:
                add(i, j, "shared")

    return [
        {"source": a, "target": b, "kind": "mention" if "mention" in kinds else "shared"}
        for (a, b), kinds in sorted(pairs.items())
    ]


def make_node(i, note):
    return {"id": i, "label": note["label"], "group": note["group"], "path": note["path"],
            "excerpt": make_excerpt(note["text"])}


def build_graph(notes):
    nodes = [make_node(i, n) for i, n in enumerate(notes)]
    return {"nodes": nodes, "links": build_links(notes)}


def links_for(notes, i):
    """The links build_links gives note i, computed against every other note."""
    return [l for l in build_links(notes) if i in (l["source"], l["target"])]


def write_graph(graph, out_file=OUT_FILE):
    """Write graph-data.js atomically, so a page reload never reads a half-written file."""
    os.makedirs(os.path.dirname(out_file), exist_ok=True)
    tmp = out_file + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("// Generated by build.py. Do not edit by hand.\n")
        f.write("const GRAPH = ")
        json.dump(graph, f, ensure_ascii=False, indent=1)
        f.write(";\n")
    os.replace(tmp, out_file)


def main():
    notes = load_notes()
    graph = build_graph(notes)
    write_graph(graph)
    print(f"Indexed {len(graph['nodes'])} notes, {len(graph['links'])} links -> "
          f"{os.path.relpath(OUT_FILE, ROOT)}")


if __name__ == "__main__":
    main()
